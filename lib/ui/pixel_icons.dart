/// Draws one of [pixelIcons] with crisp square pixels.
class PixelIcon extends StatelessWidget {
  const PixelIcon(this.name, {super.key, this.size = 16, this.semanticLabel});

  final String name;
  final double size;
  final String? semanticLabel;

  @override
  Widget build(BuildContext context) {
    final grid = pixelIcons[name]!;
    final cols = grid.first.length;
    final rows = grid.length;
    final scale = size / (cols > rows ? cols : rows);
    final icon = CustomPaint(
      size: Size(cols * scale, rows * scale),
      painter: _PixelPainter(grid),
    );
    if (semanticLabel == null) return ExcludeSemantics(child: icon);
    return Semantics(label: semanticLabel, image: true, child: icon);
  }
}

class _PixelPainter extends CustomPainter {
  _PixelPainter(this.grid);

  final List<String> grid;

  @override
  void paint(Canvas canvas, Size size) {
    final px = size.width / grid.first.length;
    final paint = Paint()..isAntiAlias = false;
    for (var y = 0; y < grid.length; y++) {
      final row = grid[y];
      for (var x = 0; x < row.length; x++) {
        final color = _ink[row[x]];
        if (color == null) continue;
        paint.color = color;
        // Slight overlap avoids hairline seams between pixels.
        canvas.drawRect(
          Rect.fromLTWH(x * px, y * px, px + 0.5, px + 0.5),
          paint,
        );
      }
    }
  }

  @override
  bool shouldRepaint(_PixelPainter old) => !identical(old.grid, grid);
}
